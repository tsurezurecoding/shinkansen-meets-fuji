import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = path.join(root, 'train-window-geometry.js');

// track.js は駅アンカーの分数を ROUTE から取るため、data.js と同じ文脈で読む。
const ctx = { window: {}, console };
ctx.globalThis = ctx;
vm.createContext(ctx);
vm.runInContext(
  fs.readFileSync(path.join(root, 'data.js'), 'utf8') + '\n;globalThis.__X={ROUTE,SPOTS};\n'
    + fs.readFileSync(path.join(root, 'track.js'), 'utf8') + '\n'
    ,
  ctx,
);
const { ROUTE, SPOTS } = ctx.__X;
const TRACK = ctx.window.MADO_TRACK;

const thumb = (src) => String(src).replace(/^images\/(.+)\.(jpe?g|png)$/i, 'images/thumbs/$1.webp');
const round = (v, d = 1) => Math.round(v * 10 ** d) / 10 ** d;

// 線路: 経度をcos(緯度)で縮め、北を上にした平面へ。RDPで間引く。
const LAT0 = 35;
const k = Math.cos((LAT0 * Math.PI) / 180);
const proj = (lat, lng) => ({ x: lng * k, y: -lat });
const raw = TRACK.points.map((p) => ({ ...proj(p.lat, p.lng), km: p.km }));
function rdp(pts, eps) {
  if (pts.length < 3) return pts;
  const a = pts[0], b = pts[pts.length - 1];
  const dx = b.x - a.x, dy = b.y - a.y, len = Math.hypot(dx, dy) || 1e-9;
  let max = 0, idx = 0;
  for (let i = 1; i < pts.length - 1; i++) {
    const d = Math.abs(dy * pts[i].x - dx * pts[i].y + b.x * a.y - b.y * a.x) / len;
    if (d > max) { max = d; idx = i; }
  }
  if (max <= eps) return [a, b];
  return rdp(pts.slice(0, idx + 1), eps).slice(0, -1).concat(rdp(pts.slice(idx), eps));
}
const simple = rdp(raw, 0.0016);
const minX = Math.min(...raw.map((p) => p.x)), maxX = Math.max(...raw.map((p) => p.x));
const minY = Math.min(...raw.map((p) => p.y)), maxY = Math.max(...raw.map((p) => p.y));
const W = 1000, scale = W / (maxX - minX), H = Math.round((maxY - minY) * scale);
const toView = (p) => [round((p.x - minX) * scale), round((p.y - minY) * scale)];

const kmAtMin = (min) => TRACK.minToKm(min);
const spotKm = (s) => {
  const pos = s.viewpoint || s.map;
  if (pos && typeof pos.lat === 'number') return TRACK.projectToTrack(pos.lat, pos.lng).km;
  return kmAtMin(s.minutesFromTokyo);
};

const spots=SPOTS.map(s=>({id:s.id,n:s.ja.name,h:s.ja.hook||'',m:s.minutesFromTokyo,km:round(spotKm(s),2),s:s.sideLabel&&/A.*E|E.*A/.test(s.sideLabel.ja||'')?'AE':s.side,...(s.map?{xy:toView(proj(s.map.lat,s.map.lng))}:{})})).sort((a,b)=>a.km-b.km);
const anchors=TRACK.anchors();
const stations=ROUTE.refStations.map(st=>{const an=anchors.find(a=>a.id===st.id),km=an?an.km:kmAtMin(st.min),ll=TRACK.latLngAtKm(km);return{id:st.id,n:st.ja,m:st.min,km:round(km,2),major:!!st.major,xy:toView(proj(ll.lat,ll.lng))};});
const data={generatedFrom:'data.js + track.js',totalKm:round(TRACK.totalKm,2),view:{w:W,h:H},line:simple.map(p=>[...toView(p),round(p.km,2)]),stations,spots};
const body='/* Generated by scripts/generate-train-window-geometry.mjs. */\nwindow.MADO_TRAIN_WINDOW = '+JSON.stringify(data)+';\n';
if(process.argv.includes('--check')){if(!fs.existsSync(out)||fs.readFileSync(out,'utf8')!==body){console.error('train-window-geometry.js is stale');process.exit(1);}}else if(!fs.existsSync(out)||fs.readFileSync(out,'utf8')!==body)fs.writeFileSync(out,body,'utf8');
console.log('Train-window geometry: '+stations.length+' stations, '+spots.length+' current spots');
