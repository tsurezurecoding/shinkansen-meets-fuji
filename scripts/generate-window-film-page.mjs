// Self-hosted subsets cover the glyphs the film used when they were cut; a new spot name may add more.
const glyphFile = path.join(root, 'fonts/window-film/glyphs.txt');
if (fs.existsSync(glyphFile)) {
  const covered = new Set(Array.from(fs.readFileSync(glyphFile, 'utf8')));
  const missing = [...new Set(Array.from(cast.map((r) => r.ja + r.en + r.hj + r.he).join('')))].filter((ch) => ch.trim() && !covered.has(ch));
  if (missing.length) console.warn(`window-film: ${missing.length} glyphs fall back to system fonts (${missing.join('')}); rerun scripts/subset-window-film-fonts.py`);
}
console.log(`Window film: ${changed} changed; ${cast.length} cast, ${stamps.length} stamps.`);
